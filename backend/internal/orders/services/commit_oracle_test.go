// 用户实际报错的 Oracle 工单：故意用保留字表名（ORDER）/保留字列名（DESC）、
// NUMBER...AS IDENTITY 自增列、CHAR/VARCHAR2、中文行内注释 —— 每一项都该由
// 规范预审报出来，而不是在「保存并提交」阶段被 TiDB parser 拦截。
const oracleOrderSQL = `-- 触发：表名不能是关键字、表名的大小写、表必须有注释、字段名的大小写
CREATE TABLE ORDER (
-- 触发：自增列名为 ID（此处用了 seq_no）
seq_no NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
-- 触发：字段名不能是关键字（使用了 DESC）
DESC VARCHAR2(50),
-- 触发：CHAR 类型字段的长度（通常要求定长或特定长度）
is_valid CHAR(1),
-- 触发：VARCHAR 类型字段的长度（可能要求必须是 2 的倍数，或者有最大长度限制）
user_name VARCHAR2(500),
-- 触发：列必须有注释（缺少 COMMENT ON COLUMN）
create_time DATE
-- 触发：表必须有主键（如果上面没写 PRIMARY KEY）
-- 触发：表字段数量上限（如果字段极多）
);
-- 触发：表必须包含指定列（比如规范要求必须有 tenant_id、create_time、update_time）`

// 修复前：CreateOrderService.Run 的 SQL 条数校验对非 PG 类一律走 TiDB parser
// （CheckMaxAllowedSQLNums），Oracle 语法直接报「SQL解析错误」，工单无法保存。
func TestOracleOrderTypeInference(t *testing.T) {
	sqlType, err := inferOrderSQLType(oracleOrderSQL, "Oracle")
	if err != nil {
		t.Fatalf("Oracle 工单类型推断失败（保存第一步）: %v", err)
	}
	if sqlType != "DDL" {
		t.Fatalf("期望 DDL，实际 %s", sqlType)
	}
}

func TestOracleOrderTargetMode(t *testing.T) {
	mode, err := detectOrderTargetMode(oracleOrderSQL, "Oracle")
	if err != nil {
		t.Fatalf("Oracle 工单目标模式判断失败: %v", err)
	}
	if mode != orderTargetSchema {
		t.Fatalf("期望 schema 模式，实际 %s", mode)
	}
}

// 保存链路的条数计数：Oracle 走 sqlsplit.Split（语法感知拆分），不再依赖 TiDB parser
func TestOracleOrderSQLCount(t *testing.T) {
	if tidbParserCompatibleDB("Oracle") {
		t.Fatal("Oracle 不应被判定为 TiDB parser 兼容")
	}
	n := len(sqlsplit.Split(oracleOrderSQL))
	if n != 1 {
		t.Fatalf("期望拆出 1 条语句，实际 %d", n)
	}
}

// MySQL 链路保持 TiDB parser 口径（行为不变）
func TestMySQLParserCompatibleUnchanged(t *testing.T) {
	for _, db := range []string{"MySQL", "TiDB", "Doris"} {
		if !tidbParserCompatibleDB(db) {
			t.Fatalf("%s 应保持 TiDB parser 兼容", db)
		}
	}
	for _, db := range []string{"PostgreSQL", "SQLServer", "Oracle", ""} {
		if tidbParserCompatibleDB(db) {
			t.Fatalf("%s 不应走 TiDB parser", db)
		}
	}
	// 说明性断言：TiDB parser 确实解析不了 Oracle 语法（修复前保存被拦的直接原因）
	if err := parser.CheckMaxAllowedSQLNums(oracleOrderSQL); err == nil {
		t.Fatal("TiDB parser 竟然解析通过了 Oracle 保留字建表，需复核测试前提")
	}
}
